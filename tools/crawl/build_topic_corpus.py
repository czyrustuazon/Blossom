# --- row filters ---------------------------------------------------------------------
_SKIP_PATH_RE = re.compile(
    r"(^|/)(vendor|vendors|third_party|thirdparty|3rdparty|external|deps|node_modules|bower_components|"
    r"dist|build|out|target|bin|obj|\.git|__pycache__|site-packages|fixtures?|testdata|test_data|"
    r"snapshots?|__snapshots__|generated|gen|autogen|migrations)/"
    r"|\.min\.(js|css)$|\.bundle\.js$|-lock\.(json|yaml)$|\.lock$|(^|/)(package-lock|yarn|pnpm-lock)\.|"
    r"_pb2(_grpc)?\.py$|\.pb\.(go|cc|h)$|\.g\.dart$|\.designer\.cs$|(^|/)(LICENSE|LICENCE|COPYING|NOTICE|"
    r"AUTHORS|CHANGELOG|CHANGES)(\.\w+)?$",
    re.I,
)
_LICENSE_RE = re.compile(
    r"Permission is hereby granted, free of charge|Licensed under the Apache License|GNU (?:Lesser )?General "
    r"Public License|Redistribution and use in source and binary forms|THE SOFTWARE IS PROVIDED \"AS IS\"",
    re.I,
)
_GENERATED_RE = re.compile(r"(?:auto-?generated|do not edit|generated by|@generated)", re.I)


def looks_binary(text: str) -> bool:
    """Mis-decoded bodies (compressed pages stored as text: citro2d.devkitpro.org in the 2026-11
    crawl) — many U+FFFD replacement or control characters."""
    sample = text[:4000]
    if not sample:
        return False
    bad = sum(1 for ch in sample if ch == "\ufffd" or (ord(ch) < 32 and ch not in "\t\n\r"))
    return bad / len(sample) > 0.02


def skip_reason(text: str, path: str) -> str | None:
    if _SKIP_PATH_RE.search(path or ""):
        return "path"
    if looks_binary(text):
        return "binary"
    body = strip_crawl_header(text)
    n = nws_len(body)
    if n < 40:
        return "tiny"
    lines = body.split("\n")
    longest = max((len(line) for line in lines), default=0)
    if longest > 1500 or (len(body) / max(1, len(lines)) > 220):
        return "minified"
    head = body[:600]
    if _GENERATED_RE.search(head):
        return "generated"
    if _LICENSE_RE.search(body):
        code_lines = sum(1 for line in lines if line.strip() and not line.lstrip().startswith(("#", "//", "*", "/*", "--", ";")))
        if code_lines < 5:
            return "license"
    return None


def est_parts(text: str) -> int:
    return max(1, math.ceil(nws_len(strip_crawl_header(text)) / DEFAULT_BUDGET * 1.15))


# --- sqlite --------------------------------------------------------------------------

SCHEMA = """
CREATE TABLE IF NOT EXISTS cand (
  src TEXT, off INTEGER, len INTEGER, coll TEXT, repo TEXT, stars INTEGER, parts INTEGER,
  kind TEXT, lang TEXT, hash TEXT UNIQUE, picked INTEGER DEFAULT 0
);
CREATE INDEX IF NOT EXISTS cand_coll ON cand(coll);
CREATE TABLE IF NOT EXISTS ranges (src TEXT, start INTEGER, PRIMARY KEY (src, start));
CREATE TABLE IF NOT EXISTS skips (reason TEXT PRIMARY KEY, n INTEGER);
"""


def db(work: Path) -> sqlite3.Connection:
    work.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(work / "candidates.sqlite")
    con.executescript(SCHEMA)
    con.execute("PRAGMA journal_mode=WAL")
    con.execute("PRAGMA synchronous=NORMAL")
    return con


def _count_skip(skips: dict[str, int], reason: str) -> None:
    skips[reason] = skips.get(reason, 0) + 1


def _flush_skips(con: sqlite3.Connection, skips: dict[str, int]) -> None:
    for reason, n in skips.items():
        con.execute(
            "INSERT INTO skips(reason, n) VALUES(?, ?) ON CONFLICT(reason) DO UPDATE SET n = n + excluded.n",
            (reason, n),
        )
    skips.clear()


RANGE_BYTES = 128 * 1024 * 1024
INSERT_SQL = (
    "INSERT OR IGNORE INTO cand(src, off, len, coll, repo, stars, parts, kind, lang, hash) "
    "VALUES (?,?,?,?,?,?,?,?,?,?)"
)


def classify_range(path_s: str, start: int, end: int, github: bool, limit_rows: int = 0):
    """Worker: candidates for the lines that start in [start, end). Returns (rows, skips, n)."""
    path = Path(path_s)
    src = path.name
    rows: list[tuple] = []
    skips: dict[str, int] = {}
    # README/doc rows in a GitHub repo get the repo's dominant language; a repo's rows are
    # contiguous in rag_github, so its docs wait in a small buffer until the repo changes.
    repo_docs: list[tuple] = []
    repo_langs: dict[str, int] = {}
    current_repo = ""
    seen = 0

    def flush_repo() -> None:
        if not repo_docs:
            return
        lang = max(repo_langs, key=repo_langs.get) if repo_langs else ""
        coll = CrawlTopics.code_collection(lang) if lang else None
        for off, ln, repo, stars, parts, h, topic in repo_docs:
            target = topic or coll
            if target:
                rows.append((src, off, ln, target, repo, stars, parts, "documentation", lang, h))
            else:
                _count_skip(skips, "doc_no_language")
        repo_docs.clear()

    with path.open("rb") as handle:
        off = start
        if start > 0:
            handle.seek(start - 1)
            off = start - 1 + len(handle.readline())  # move to the first line starting >= start
        else:
            handle.seek(0)
        while off < end:
            if limit_rows and seen >= limit_rows:
                break
            line = handle.readline()
            if not line:
                break
            here, ln = off, len(line)
            off += ln
            seen += 1
            try:
                rec = _loads(line)
            except Exception:  # noqa: BLE001
                _count_skip(skips, "bad_json")
                continue
            if rec.get("action", "upsert") != "upsert":
                _count_skip(skips, "delete_action")
                continue
            text = rec.get("text") or ""
            meta = rec.get("metadata") or {}
            kind = rec.get("kind") or ""
            h = str(meta.get("content_hash") or "") or hashlib.blake2b(
                text.encode("utf-8", "replace"), digest_size=16
            ).hexdigest()
            if github:
                repo = str(meta.get("repo") or "")
                if repo != current_repo:
                    flush_repo()
                    current_repo, repo_langs = repo, {}
                p = str(meta.get("path") or "")
                reason = skip_reason(text, p)
                if reason:
                    _count_skip(skips, reason)
                    continue
                stars = int(meta.get("stars") or 0)
                coll = CrawlTopics.classify_github_row(meta, text)
                if kind == "documentation":
                    topic = coll if coll in CrawlTopics.TOPIC_COLLECTIONS else None
                    repo_docs.append((here, ln, repo, stars, est_parts(text), h, topic))
                    continue
                if not coll:
                    _count_skip(skips, f"lang:{(meta.get('language') or '?')}")
                    continue
                slug = CrawlTopics.language_slug(meta.get("language"), p)
                if slug:
                    repo_langs[slug] = repo_langs.get(slug, 0) + 1
                rows.append((src, here, ln, coll, repo, stars, est_parts(text), kind, str(meta.get("language") or ""), h))
            else:
                url = str(meta.get("canonical_url") or meta.get("url") or "")
                if nws_len(text) < 40:
                    _count_skip(skips, "tiny")
                    continue
                if looks_binary(text):
                    _count_skip(skips, "binary")
                    continue
                coll, _extra = CrawlTopics.classify_doc_url(url)
                host = re.sub(r"^https?://", "", url).split("/")[0]
                rows.append((src, here, ln, coll, host, 0, est_parts(text), kind, str(meta.get("language") or ""), h))
        flush_repo()
    return rows, skips, seen


def _range_job(job):
    path_s, start, end, github, limit_rows = job
    rows, skips, seen = classify_range(path_s, start, end, github, limit_rows)
    return start, rows, skips, seen


def scan_file(con: sqlite3.Connection, path: Path, *, github: bool, limit_rows: int = 0, workers: int = 1) -> None:
    """Scan one crawl file in byte ranges (parallel, resumable per range)."""
    src = path.name
    size = path.stat().st_size
    con.execute("CREATE TABLE IF NOT EXISTS ranges (src TEXT, start INTEGER, PRIMARY KEY (src, start))")
    if limit_rows:
        jobs = [(str(path), 0, size, github, limit_rows)]
    else:
        done = {r[0] for r in con.execute("SELECT start FROM ranges WHERE src = ?", (src,))}
        jobs = [
            (str(path), start, min(size, start + RANGE_BYTES), github, 0)
            for start in range(0, size, RANGE_BYTES)
            if start not in done
        ]
    if not jobs:
        print(f"{src}: already scanned")
        return
    total = len(jobs)
    t0 = time.perf_counter()
    rows_seen = 0

    def store(start, rows, skips, seen):
        nonlocal rows_seen
        con.executemany(INSERT_SQL, rows)
        _flush_skips(con, skips)
        if not limit_rows:
            con.execute("INSERT OR IGNORE INTO ranges(src, start) VALUES(?, ?)", (src, start))
        con.commit()
        rows_seen += seen

    if workers > 1 and total > 1:
        from multiprocessing import Pool

        with Pool(workers) as pool:
            for i, (start, rows, skips, seen) in enumerate(pool.imap_unordered(_range_job, jobs), 1):
                store(start, rows, skips, seen)
                print(f"{src}: range {i}/{total} ({rows_seen:,} rows, {time.perf_counter() - t0:.0f}s)", flush=True)
    else:
        for i, job in enumerate(jobs, 1):
            store(*_range_job(job))
            print(f"{src}: range {i}/{total} ({rows_seen:,} rows, {time.perf_counter() - t0:.0f}s)", flush=True)
    print(f"{src}: scan done ({rows_seen:,} rows, {time.perf_counter() - t0:.0f}s)")


def cmd_scan(args) -> None:
    con = db(args.work)
    out = args.crawl_out
    # Docs first (small); rag_docs before rag_corpus so its rows win the content_hash dedupe.
    # rag_targeted / rag_github_targeted come from the crawler's config.targeted.yaml run.
    for name in ("rag_docs.jsonl", "rag_corpus.jsonl", "rag_code.jsonl", "rag_targeted.jsonl"):
        if (out / name).exists():
            scan_file(con, out / name, github=False, limit_rows=args.limit_rows, workers=args.workers)
    if args.docs_only:
        return
    for name in ("rag_github_targeted.jsonl", "rag_github.jsonl"):
        if (out / name).exists():
            scan_file(con, out / name, github=True, limit_rows=args.limit_rows, workers=args.workers)


def cmd_select(args) -> None:
    con = db(args.work)
    con.execute("UPDATE cand SET picked = 0")
    report = []
    for coll, avail_rows, avail_parts in con.execute(
        "SELECT coll, COUNT(*), SUM(parts) FROM cand GROUP BY coll ORDER BY coll"
    ).fetchall():
        budget = int(BUDGETS.get(coll, 30_000) * args.scale)
        repo_cap = max(REPO_CAP_MIN, int(budget * REPO_CAP_SHARE))
        used = 0
        per_repo: dict[str, int] = {}
        picked: list[int] = []
        # Stars first for code; docs have no stars, so a hash order spreads picks across pages.
        for rowid, repo, parts, src in con.execute(
            "SELECT rowid, repo, parts, src FROM cand WHERE coll = ? ORDER BY stars DESC, hash", (coll,)
        ):
            if used >= budget:
                break
            # Cap per GitHub repo only; a docs site (ffmpeg.org, rizin.re) is one "repo" by host.
            if src.startswith("rag_github") and per_repo.get(repo, 0) + parts > repo_cap:
                continue
            per_repo[repo] = per_repo.get(repo, 0) + parts
            used += parts
            picked.append(rowid)
        con.executemany("UPDATE cand SET picked = 1 WHERE rowid = ?", ((r,) for r in picked))
        report.append((coll, avail_rows, avail_parts or 0, len(picked), used, budget, len(per_repo)))
    con.commit()
    print(f"{'collection':24} {'rows avail':>10} {'parts avail':>11} {'rows picked':>11} {'parts':>9} {'budget':>9} {'sources':>7}")
    tot = [0, 0, 0, 0]
    for coll, ar, ap, pr, pp, b, srcs in report:
        print(f"{coll:24} {ar:10,} {ap:11,} {pr:11,} {pp:9,} {b:9,} {srcs:7,}")
        tot = [tot[0] + ar, tot[1] + ap, tot[2] + pr, tot[3] + pp]
    print(f"{'TOTAL':24} {tot[0]:10,} {tot[1]:11,} {tot[2]:11,} {tot[3]:9,}")
    skips = con.execute("SELECT reason, n FROM skips ORDER BY n DESC LIMIT 15").fetchall()
    if skips:
        print("skipped rows: " + ", ".join(f"{r} {n:,}" for r, n in skips))


def cmd_split(args) -> None:
    con = db(args.work)
    split_dir = args.work / "split"
    split_dir.mkdir(parents=True, exist_ok=True)
    handles: dict[str, object] = {}
    files: dict[str, object] = {}
    counts: dict[str, int] = {}
    methods: dict[str, int] = {}
    t0 = time.perf_counter()
    try:
        for src, in con.execute("SELECT DISTINCT src FROM cand WHERE picked = 1").fetchall():
            path = args.crawl_out / src
            files[src] = path.open("rb")
        rows = con.execute(
            "SELECT src, off, len, coll, lang, kind FROM cand WHERE picked = 1 ORDER BY src, off"
        )
        for n, (src, off, ln, coll, lang, kind) in enumerate(rows, 1):
            fh = files[src]
            fh.seek(off)
            rec = _loads(fh.read(ln))
            meta = rec.get("metadata") or {}
            text = rec.get("text") or ""
            if looks_binary(text):  # rows scanned before the binary filter existed
                methods["binary_skipped"] = methods.get("binary_skipped", 0) + 1
                continue
            path_s = str(meta.get("path") or "")
            parts, method = chunk_text(text, language=meta.get("language") or lang, path=path_s, kind=kind)
            methods[method] = methods.get(method, 0) + 1
            where = f"{meta.get('repo')}/{path_s}" if meta.get("repo") else str(meta.get("url") or "")
            extra = {}
            if coll == "crawl_mslearn":
                _c, extra = CrawlTopics.classify_doc_url(str(meta.get("url") or ""))
            out = handles.get(coll)
            if out is None:
                out = handles[coll] = (split_dir / f"{coll}.jsonl").open("w", encoding="utf-8")
            for i, part in enumerate(parts):
                body = stamp(part, where=where, language=str(meta.get("language") or ""))
                pm = {
                    k: meta[k]
                    for k in ("url", "repo", "path", "language", "stars", "chunk_index", "section", "content_hash")
                    if meta.get(k) not in (None, "")
                }
                pm.update(extra)
                pm.update({"source": "web_crawl", "kind": kind, "part": i, "parts": len(parts), "chunker": method})
                if part.scope:
                    pm["scope"] = ".".join(part.scope)[:200]
                out.write(json.dumps({"id": f"{rec.get('id')}#p{i}", "text": body, "metadata": pm}, ensure_ascii=False) + "\n")
                counts[coll] = counts.get(coll, 0) + 1
            if n % 20000 == 0:
                print(f"split {n:,} rows, {sum(counts.values()):,} parts ({n / (time.perf_counter() - t0):.0f} rows/s)", flush=True)
    finally:
        for h in list(handles.values()) + list(files.values()):
            h.close()
    print(f"split done: {sum(counts.values()):,} parts, methods {methods}")
    for coll in sorted(counts):
        print(f"  {coll:24} {counts[coll]:9,}")


def cmd_import(args) -> None:
    split_dir = args.work / "split"
    if args.real_mind:
        # Build the live crawl store as a staging copy; the running router never opens it.
        # promote moves it to Mind/assistant/crawl_chromadb (restart the Assistant router after).
        os.environ["CRAWL_CHROMA_DIR"] = str(args.work / "crawl_chromadb_staging")
    else:
        os.environ["BLOSSOM_MIND_ROOT"] = str(args.work / "mind")
    import MindStores
    import SemanticMemory
    from MindStores import SURFACE_ASSISTANT

    wanted = set(filter(None, (args.collections or "").split(",")))
    prog_path = args.work / ("import_progress_real.json" if args.real_mind else "import_progress.json")
    progress = json.loads(prog_path.read_text()) if prog_path.exists() else {}
    print(f"importing into {SemanticMemory.crawl_store_dir(SURFACE_ASSISTANT)}")
    for path in sorted(split_dir.glob("crawl_*.jsonl")):
        coll_name = path.stem
        if wanted and coll_name not in wanted:
            continue
        coll = SemanticMemory._get_collection(coll_name, surface=SURFACE_ASSISTANT)
        skip = int(progress.get(coll_name, 0))
        ids, docs, metas = [], [], []
        done = skip
        t0 = time.perf_counter()
        with path.open(encoding="utf-8") as fh:
            for i, line in enumerate(fh):
                if i < skip:
                    continue
                rec = json.loads(line)
                ids.append(rec["id"])
                docs.append(rec["text"])
                metas.append(rec["metadata"])
                if len(ids) >= 256:
                    coll.upsert(ids=ids, documents=docs, metadatas=metas)
                    done += len(ids)
                    ids, docs, metas = [], [], []
                    progress[coll_name] = done
                    prog_path.write_text(json.dumps(progress))
                    if done % 5120 == 0:
                        rate = (done - skip) / (time.perf_counter() - t0)
                        print(f"{coll_name}: {done:,} ({rate:.0f}/s)", flush=True)
                    if args.limit and done - skip >= args.limit:
                        break
        if ids:
            coll.upsert(ids=ids, documents=docs, metadatas=metas)
            done += len(ids)
            progress[coll_name] = done
            prog_path.write_text(json.dumps(progress))
        print(f"{coll_name}: {done:,} in collection run")


def cmd_promote(args) -> None:
    """Move the finished staging store to the live crawl store path (router stopped or restarted after)."""
    sys.path.insert(0, str(ROOT / "PythonScripts"))
    import SemanticMemory
    from MindStores import SURFACE_ASSISTANT

    staging = args.work / "crawl_chromadb_staging"
    live = SemanticMemory.crawl_store_dir(SURFACE_ASSISTANT)
    if not staging.is_dir():
        raise SystemExit(f"no staging store at {staging}")
    if live.exists():
        backup = live.with_name(live.name + time.strftime(".old-%Y%m%d-%H%M%S"))
        live.rename(backup)
        print(f"previous live store kept at {backup}")
    staging.rename(live)
    print(f"promoted {staging} -> {live}; restart the Assistant router")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--work", type=Path, default=DEFAULT_WORK)
    ap.add_argument("--crawl-out", type=Path, default=DEFAULT_CRAWL_OUT)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("scan")
    s.add_argument("--limit-rows", type=int, default=0, help="stop each file after N rows (trial runs)")
    s.add_argument("--docs-only", action="store_true")
    s.add_argument("--workers", type=int, default=max(1, min(8, (os.cpu_count() or 2) // 4)))
    s = sub.add_parser("select")
    s.add_argument("--scale", type=float, default=1.0, help="multiply every budget")
    sub.add_parser("split")
    s = sub.add_parser("import")
    s.add_argument("--collections", default="")
    s.add_argument("--real-mind", action="store_true", help="write Mind/assistant (ask the user first)")
    s.add_argument("--limit", type=int, default=0, help="max parts per collection this run")
    sub.add_parser("promote")
    args = ap.parse_args()
    {"scan": cmd_scan, "select": cmd_select, "split": cmd_split, "import": cmd_import, "promote": cmd_promote}[args.cmd](args)


if __name__ == "__main__":
    main()
