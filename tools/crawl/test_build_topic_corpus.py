"""Row filters of the topic importer (vendored / minified / license-only / binary)."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_topic_corpus import est_parts, looks_binary, skip_reason  # noqa: E402

CODE = "def total(items):\n    return sum(i.price for i in items)\n\n" * 3


def test_real_code_is_kept():
    assert skip_reason(CODE, "shop/cart.py") is None


def test_vendored_generated_and_lock_paths_are_dropped():
    for path in ("vendor/lib/a.py", "web/node_modules/x/index.js", "app.min.js", "proto/x_pb2.py", "package-lock.json", "LICENSE"):
        assert skip_reason(CODE, path) == "path", path


def test_minified_and_generated_bodies_are_dropped():
    assert skip_reason("var a=1;" * 400, "app.js") == "minified"
    assert skip_reason("// Code generated by protoc-gen-go. DO NOT EDIT.\n" + CODE, "x.go") == "generated"


def test_license_only_rows_are_dropped_but_code_with_a_header_is_kept():
    mit = "# Permission is hereby granted, free of charge, to any person obtaining a copy\n# of this software\n" * 3
    assert skip_reason(mit, "src/a.py") == "license"
    assert skip_reason(mit + CODE * 2, "src/a.py") is None


def test_binary_bodies_are_dropped():
    garbage = "��A2\x01\x02�}�H" * 80
    assert looks_binary(garbage)
    assert skip_reason(garbage, "README.md") == "binary"
    assert not looks_binary("café naïve — fine unicode text " * 20)


def test_part_estimate_grows_with_size():
    assert est_parts("x = 1\n") == 1
    assert est_parts("value = compute(a, b)\n" * 200) > 5
