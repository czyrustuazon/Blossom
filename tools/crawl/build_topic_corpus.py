#!/usr/bin/env python3
"""Curate the crawl into per-topic Chroma collections, split with cAST.

Stages (each resumable, state in <work>/candidates.sqlite):

  scan    Stream rag_github.jsonl (+ rag_docs / rag_corpus / rag_code). Drop vendored, generated,
          minified, lock, fixture and license-only rows and dropped languages; classify each row
          into a collection (CrawlTopics.py); dedupe by content_hash; index (file, offset).
  select  Pick rows per collection up to its budget in cAST parts: higher stars first, a cap per
          repo so one big repo cannot fill a language, small collections keep everything.
          Prints the per-collection counts — read them before importing.
  split   cAST-split the selected rows into <work>/split/<collection>.jsonl (one part per line,
          stamped with repo/path and enclosing scope).
  import  Embed the split files into Chroma. Default target is a scratch Mind under <work>;
          --real-mind writes Mind/assistant (needs the user's OK; hours on the CPU embedder).

  python tools/crawl/build_topic_corpus.py scan   --crawl-out C:/Users/Zepse/Documents/rag-web-crawler/out
  python tools/crawl/build_topic_corpus.py select [--scale 1.0]
  python tools/crawl/build_topic_corpus.py split
  python tools/crawl/build_topic_corpus.py import [--collections crawl_3ds,...] [--real-mind]
"""

